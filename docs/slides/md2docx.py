#!/usr/bin/env python3
"""Convert markdown slides to Word document."""

from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
import re

def parse_markdown_to_docx(md_path, docx_path):
    """Parse markdown and create Word document."""
    with open(md_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    doc = Document()
    
    # Set default styles
    style = doc.styles['Normal']
    style.font.name = 'Calibri'
    style.font.size = Pt(11)
    
    # Colors
    PRIMARY = RGBColor(21, 101, 192)
    
    # Split by horizontal rule
    slides = re.split(r'\n---\n', content)
    
    current_table = None
    in_code_block = False
    code_lines = []
    
    for i, slide in enumerate(slides):
        lines = slide.strip().split('\n')
        
        for line in lines:
            line = line.strip()
            if not line:
                continue
            
            # Skip header info
            if line.startswith('**Đại học Đà Lạt'):
                continue
            if line.startswith('*Generated by'):
                continue
            
            # Main title
            if line.startswith('# ITDLUPanel') or line.startswith('# PHẦN'):
                p = doc.add_heading(line.replace('# ', '').replace('#', ''), 0)
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                continue
            
            # Section headers (## Slide)
            if line.startswith('## Slide'):
                p = doc.add_heading(line.replace('## ', ''), 1)
                continue
            
            # Sub-headers
            if line.startswith('### '):
                p = doc.add_paragraph(line.replace('### ', ''))
                p.runs[0].bold = True
                p.runs[0].font.color.rgb = PRIMARY
                continue
            
            # Code block start/end
            if line.startswith('```'):
                if in_code_block:
                    # Add collected code
                    code_text = '\n'.join(code_lines)
                    p = doc.add_paragraph()
                    run = p.add_run(code_text)
                    run.font.name = 'Courier New'
                    run.font.size = Pt(9)
                    p.paragraph_format.left_indent = Inches(0.3)
                    code_lines = []
                in_code_block = not in_code_block
                continue
            
            if in_code_block:
                code_lines.append(line)
                continue
            
            # Bullet points
            if line.startswith('- '):
                p = doc.add_paragraph(line[2:], style='List Bullet')
                continue
            
            # Table rows
            if line.startswith('|'):
                cells = [c.strip() for c in line.split('|')[1:-1]]
                if not any(cells):
                    continue
                
                # Skip separator row
                if all('-' in c or c == '' for c in cells):
                    continue
                
                # Check if header row
                is_header = not any('-' in c for c in cells)
                
                if is_header:
                    # Create new table
                    table = doc.add_table(rows=1, cols=len(cells))
                    table.style = 'Table Grid'
                    header_row = table.rows[0]
                    for j, cell in enumerate(cells):
                        cell_obj = header_row.cells[j]
                        cell_obj.text = cell
                        cell_obj.paragraphs[0].runs[0].bold = True
                        cell_obj.paragraphs[0].runs[0].font.color.rgb = PRIMARY
                else:
                    # Add row to existing table
                    if doc.tables:
                        table = doc.tables[-1]
                        row = table.add_row()
                        for j, cell in enumerate(cells[:len(row.cells)]):
                            row.cells[j].text = cell
                continue
            
            # Regular paragraph
            if line:
                # Check for bold text
                parts = re.split(r'(\*\*[^*]+\*\*|\*[^*]+\*)', line)
                p = doc.add_paragraph()
                for part in parts:
                    clean = part.replace('**', '').replace('*', '')
                    if clean:
                        run = p.add_run(clean)
                        if '**' in part:
                            run.bold = True
        
        # Add page break between slides (except last)
        if i < len(slides) - 1:
            doc.add_page_break()
    
    doc.save(docx_path)
    print(f"DOCX created: {docx_path}")

if __name__ == '__main__':
    md_path = '/root/ITDLUPanel/docs/slides/ITDLUPanel-Presentation-Combined.md'
    docx_path = '/root/ITDLUPanel/docs/slides/ITDLUPanel-Presentation-Combined.docx'
    parse_markdown_to_docx(md_path, docx_path)
